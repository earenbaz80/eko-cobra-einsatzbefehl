export function computeLoadoutMetrics(plan: MissionPlan) {
  const profile = EKO_COBRA_PROFILES[plan.profile];
  const weapon = EKO_COBRA_WEAPONS[plan.primaryWeapon];
  const attachment = EKO_COBRA_ATTACHMENTS[plan.attachment ?? 'NONE'];
  const inspection = EKO_COBRA_INSPECTION_DEVICES[plan.inspectionDevice];
  const gadget = EKO_COBRA_GADGETS[plan.gadget];

  const attachmentWeight = attachment.id === 'SUPPRESSOR' ? 0.45 : attachment.id === 'RED_DOT_LASER' ? 0.25 : attachment.id === 'IR_LASER' ? 0.18 : 0;
  const totalGadgets = gadget.baseCount + profile.extraGadgets;
  const baseRigKg = 7.2 + (profile.armorBonus > 0 ? profile.armorBonus * 0.08 : 0);
  const totalWeightKg = +(
    baseRigKg +
    weapon.weightKg +
    attachmentWeight +
    inspection.weightKg +
    gadget.weightKg * totalGadgets
  ).toFixed(1);

  const baseSpeed = weapon.hasShield ? 3.8 : 4.8;
  const speedMetersPerSec = +(baseSpeed * profile.speedMultiplier).toFixed(1);

  const intimidationScore = Math.min(
    100,
    Math.round(40 + weapon.suppressionBonus + profile.shoutMoraleBonus + (attachment.id === 'SUPPRESSOR' ? -5 : 5))
  );

  const effectiveSensorRangeMeters = +(
    (inspection.rangePx * profile.sensorRangeMultiplier) /
    42
  ).toFixed(1);

  return {
    totalWeightKg,
    speedMetersPerSec,
    intimidationScore,
    effectiveSensorRangeMeters,
    totalGadgets,
    totalTaser: 3 + profile.extraTaser,
    totalArmor: 100 + profile.armorBonus + (weapon.hasShield ? 40 : 0),
  };
}

